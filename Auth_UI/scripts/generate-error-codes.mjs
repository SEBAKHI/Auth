/**
 * Writes packages/api/src/error-codes.generated.ts from docs/api/error-codes.json,
 * the error-code list the API publishes (ADR 0001).
 *
 * Run after the list changes: `pnpm gen:error-codes`. The client validates every
 * code it reads against the generated map, and error-codes.test.ts fails while
 * the map and the list disagree, so a code the API adds is unknown to the client
 * until this has run, never silently trusted.
 */
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const source = join(root, "docs", "api", "error-codes.json")
const target = join(root, "Auth_UI", "packages", "api", "src", "error-codes.generated.ts")

const { codes } = JSON.parse(readFileSync(source, "utf8"))

const entries = codes
  .map(({ code, source: origin, pointer }) => [code, pointer ?? origin])
  .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
  .map(([code, value]) => `  ${JSON.stringify(code)}: ${JSON.stringify(value)},`)

writeFileSync(
  target,
  [
    "/**",
    " * GENERATED by scripts/generate-error-codes.mjs from docs/api/error-codes.json.",
    " * Do not edit: run `pnpm gen:error-codes`. error-codes.test.ts fails on drift.",
    " *",
    " * Every code the API may send in a problem's `code` (ADR 0001), mapped to the",
    ' * request-body member it concerns (an RFC 6901 pointer, "#/newPassword") when it',
    ' * is a Validation code that names one, else to where it comes from: "catalog"',
    ' * for a handler error, "transport" or "challenge" for one the HTTP pipeline',
    " * produces.",
    " */",
    "export const PUBLISHED_ERROR_CODES = {",
    ...entries,
    "} as const",
    "",
    "export type PublishedErrorCode = keyof typeof PUBLISHED_ERROR_CODES",
    "",
  ].join("\n")
)

console.log(`Wrote ${entries.length} codes to ${target}`)
